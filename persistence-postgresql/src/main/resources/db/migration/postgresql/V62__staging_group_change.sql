CREATE TABLE staging_group_change (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id BIGINT NOT NULL REFERENCES staging_session(id) ON DELETE CASCADE,
  group_repository_id BIGINT NOT NULL REFERENCES repository(id) ON DELETE CASCADE,
  member_repository_id BIGINT NOT NULL REFERENCES repository(id) ON DELETE CASCADE,
  action VARCHAR(16) NOT NULL,
  position INT NULL,
  status VARCHAR(32) NOT NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_staging_group_change
    UNIQUE (session_id, group_repository_id, member_repository_id)
);
CREATE INDEX idx_staging_group_change_group
  ON staging_group_change(group_repository_id);
