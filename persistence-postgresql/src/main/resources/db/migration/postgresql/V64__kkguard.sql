CREATE TABLE kkg_organization (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  external_id CHAR(36) NOT NULL,
  name VARCHAR(255) NOT NULL,
  description VARCHAR(1024) NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_kkg_organization_external_id UNIQUE (external_id),
  CONSTRAINT uk_kkg_organization_name UNIQUE (name)
);

CREATE TABLE kkg_application (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id BIGINT NOT NULL,
  external_id CHAR(36) NOT NULL,
  public_id VARCHAR(200) NOT NULL,
  name VARCHAR(255) NOT NULL,
  repository_id BIGINT NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_kkg_application_external_id UNIQUE (external_id),
  CONSTRAINT uk_kkg_application_public_id UNIQUE (organization_id, public_id),
  CONSTRAINT fk_kkg_application_organization
    FOREIGN KEY (organization_id) REFERENCES kkg_organization(id) ON DELETE CASCADE,
  CONSTRAINT fk_kkg_application_repository
    FOREIGN KEY (repository_id) REFERENCES repository(id) ON DELETE SET NULL
);
CREATE INDEX idx_kkg_application_organization ON kkg_application(organization_id);
CREATE INDEX idx_kkg_application_repository ON kkg_application(repository_id);

CREATE TABLE kkg_scan (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id BIGINT NOT NULL,
  scan_id VARCHAR(64) NOT NULL,
  status VARCHAR(32) NOT NULL,
  stage VARCHAR(64) NULL,
  source_id VARCHAR(255) NULL,
  sbom_sha256 CHAR(64) NULL,
  report_sha256 CHAR(64) NULL,
  component_count INT NOT NULL DEFAULT 0,
  violation_count INT NOT NULL DEFAULT 0,
  error TEXT NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  started_at TIMESTAMPTZ(3) NULL,
  completed_at TIMESTAMPTZ(3) NULL,
  CONSTRAINT uk_kkg_scan_scan_id UNIQUE (scan_id),
  CONSTRAINT fk_kkg_scan_application
    FOREIGN KEY (application_id) REFERENCES kkg_application(id) ON DELETE CASCADE
);
CREATE INDEX idx_kkg_scan_application ON kkg_scan(application_id, created_at);
CREATE INDEX idx_kkg_scan_status ON kkg_scan(status, created_at);

CREATE TABLE kkg_scan_component (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scan_id BIGINT NOT NULL,
  component_ref VARCHAR(512) NOT NULL,
  purl VARCHAR(1024) NULL,
  name VARCHAR(512) NULL,
  version VARCHAR(255) NULL,
  license VARCHAR(512) NULL,
  highest_severity VARCHAR(32) NULL,
  CONSTRAINT fk_kkg_scan_component_scan
    FOREIGN KEY (scan_id) REFERENCES kkg_scan(id) ON DELETE CASCADE
);
CREATE INDEX idx_kkg_scan_component_scan ON kkg_scan_component(scan_id);

CREATE TABLE kkg_scan_finding (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scan_id BIGINT NOT NULL,
  component_ref VARCHAR(512) NOT NULL,
  vulnerability_id VARCHAR(128) NOT NULL,
  severity VARCHAR(32) NULL,
  cvss_score DECIMAL(4,1) NULL,
  source VARCHAR(128) NULL,
  description TEXT NULL,
  url VARCHAR(1024) NULL,
  CONSTRAINT fk_kkg_scan_finding_scan
    FOREIGN KEY (scan_id) REFERENCES kkg_scan(id) ON DELETE CASCADE
);
CREATE INDEX idx_kkg_scan_finding_scan ON kkg_scan_finding(scan_id, vulnerability_id);
CREATE INDEX idx_kkg_scan_finding_component ON kkg_scan_finding(scan_id, component_ref);

CREATE TABLE kkg_policy (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id BIGINT NOT NULL,
  external_id CHAR(36) NOT NULL,
  public_id VARCHAR(200) NOT NULL,
  name VARCHAR(255) NOT NULL,
  threat_level INT NOT NULL DEFAULT 5,
  constraints_json JSONB NOT NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_kkg_policy_external_id UNIQUE (external_id),
  CONSTRAINT uk_kkg_policy_public_id UNIQUE (organization_id, public_id),
  CONSTRAINT fk_kkg_policy_organization
    FOREIGN KEY (organization_id) REFERENCES kkg_organization(id) ON DELETE CASCADE
);

CREATE TABLE kkg_violation (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scan_id BIGINT NOT NULL,
  policy_id BIGINT NOT NULL,
  component_ref VARCHAR(512) NOT NULL,
  threat_level INT NOT NULL,
  constraint_json JSONB NOT NULL,
  CONSTRAINT fk_kkg_violation_scan
    FOREIGN KEY (scan_id) REFERENCES kkg_scan(id) ON DELETE CASCADE,
  CONSTRAINT fk_kkg_violation_policy
    FOREIGN KEY (policy_id) REFERENCES kkg_policy(id) ON DELETE CASCADE
);
CREATE INDEX idx_kkg_violation_scan ON kkg_violation(scan_id, policy_id);
