-- Derived inventory only: no change to component coordinates, assets or blob storage.
CREATE TABLE maven_snapshot_family (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 repository_id BIGINT NOT NULL,
 path_hash BYTEA NOT NULL,
 path VARCHAR(2048) NOT NULL,
 group_id VARCHAR(2048) NOT NULL,
 artifact_id VARCHAR(2048) NOT NULL,
 base_version VARCHAR(2048) NOT NULL,
 UNIQUE (repository_id, path_hash),
 FOREIGN KEY (repository_id) REFERENCES repository(id) ON DELETE CASCADE
);
CREATE TABLE maven_snapshot_build (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 family_id BIGINT NOT NULL,
 repository_id BIGINT NOT NULL,
 version VARCHAR(2048) NOT NULL,
 snapshot_timestamp BIGINT NOT NULL,
 build_number INTEGER NOT NULL,
 revision BIGINT NOT NULL DEFAULT 0,
 asset_count INTEGER NOT NULL DEFAULT 0,
 primary_count INTEGER NOT NULL DEFAULT 0,
 has_primary BOOLEAN GENERATED ALWAYS AS (primary_count > 0) STORED,
 mutated_at TIMESTAMP(3) WITH TIME ZONE NOT NULL,
 UNIQUE (family_id, snapshot_timestamp, build_number),
 FOREIGN KEY (family_id) REFERENCES maven_snapshot_family(id) ON DELETE CASCADE,
 FOREIGN KEY (repository_id) REFERENCES repository(id) ON DELETE CASCADE
);
CREATE INDEX idx_maven_snapshot_page ON maven_snapshot_build(repository_id, id);
CREATE INDEX idx_maven_snapshot_retained ON maven_snapshot_build(family_id, has_primary, snapshot_timestamp, build_number);
CREATE TABLE maven_snapshot_asset (
 asset_id BIGINT NOT NULL PRIMARY KEY,
 build_id BIGINT NOT NULL,
 family_id BIGINT NOT NULL,
 variant_hash BYTEA NOT NULL,
 primary_asset BOOLEAN NOT NULL,
 snapshot_timestamp BIGINT NOT NULL,
 build_number INTEGER NOT NULL,
 FOREIGN KEY (asset_id) REFERENCES asset(id) ON DELETE CASCADE,
 FOREIGN KEY (build_id) REFERENCES maven_snapshot_build(id) ON DELETE CASCADE,
 FOREIGN KEY (family_id) REFERENCES maven_snapshot_family(id) ON DELETE CASCADE
);
CREATE INDEX idx_maven_snapshot_assets ON maven_snapshot_asset(build_id, asset_id);
CREATE INDEX idx_maven_snapshot_variant ON maven_snapshot_asset
 (family_id, variant_hash, primary_asset, snapshot_timestamp, build_number);
