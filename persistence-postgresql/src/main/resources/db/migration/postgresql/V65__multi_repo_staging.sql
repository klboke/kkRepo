CREATE TABLE staging_session (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(200) NOT NULL,
  state VARCHAR(32) NOT NULL,
  revision BIGINT NOT NULL DEFAULT 0,
  owner_source VARCHAR(100) NOT NULL,
  owner_user_id VARCHAR(200) NOT NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  opened_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  frozen_at TIMESTAMPTZ(3) NULL,
  finished_at TIMESTAMPTZ(3) NULL,
  expires_at TIMESTAMPTZ(3) NULL,
  promotion_id BIGINT NULL,
  attributes_json JSONB NOT NULL,
  CONSTRAINT uk_staging_session_name UNIQUE (name)
);
CREATE INDEX idx_staging_session_state ON staging_session(state, expires_at);
CREATE INDEX idx_staging_session_owner ON staging_session(owner_source, owner_user_id);

CREATE TABLE staging_session_repository (
  session_id BIGINT NOT NULL REFERENCES staging_session(id) ON DELETE CASCADE,
  repository_id BIGINT NOT NULL REFERENCES repository(id) ON DELETE CASCADE,
  format VARCHAR(50) NOT NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (session_id, repository_id)
);
CREATE INDEX idx_staging_session_repository_repo
  ON staging_session_repository(repository_id);

CREATE TABLE staging_item (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id BIGINT NOT NULL REFERENCES staging_session(id) ON DELETE CASCADE,
  repository_id BIGINT NOT NULL REFERENCES repository(id) ON DELETE CASCADE,
  format VARCHAR(50) NOT NULL,
  logical_path VARCHAR(2048) NOT NULL,
  logical_path_hash BYTEA NOT NULL,
  action VARCHAR(16) NOT NULL,
  status VARCHAR(32) NOT NULL,
  blob_store_id BIGINT NULL,
  asset_blob_id BIGINT REFERENCES asset_blob(id) ON DELETE SET NULL,
  content_type VARCHAR(255) NULL,
  size BIGINT NULL CHECK (size IS NULL OR size >= 0),
  sha256 CHAR(64) NULL,
  md5 CHAR(32) NULL,
  sha1 CHAR(40) NULL,
  source_path VARCHAR(2048) NULL,
  expected_sha256 CHAR(64) NULL,
  expected_size BIGINT NULL CHECK (expected_size IS NULL OR expected_size >= 0),
  attributes_json JSONB NOT NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_staging_item_path UNIQUE (session_id, repository_id, logical_path_hash)
);
CREATE INDEX idx_staging_item_status ON staging_item(session_id, status);
CREATE INDEX idx_staging_item_repository ON staging_item(repository_id);
CREATE INDEX idx_staging_item_blob ON staging_item(asset_blob_id);

CREATE TABLE staging_promotion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id BIGINT NOT NULL REFERENCES staging_session(id) ON DELETE CASCADE,
  state VARCHAR(32) NOT NULL,
  fence_token VARCHAR(64) NULL,
  manifest_sha256 CHAR(64) NULL,
  report_json JSONB NULL,
  started_at TIMESTAMPTZ(3) NULL,
  finished_at TIMESTAMPTZ(3) NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_staging_promotion_session ON staging_promotion(session_id, id);
