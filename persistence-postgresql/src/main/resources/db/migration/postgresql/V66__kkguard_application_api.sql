-- kkGuard application API fields and Dependency-Track scan pipeline state.
-- Scan ownership is fenced with lease_owner/lease_expires_at so any replica can drive a scan
-- while only one replica at a time submits or completes it.

ALTER TABLE kkg_application
  ADD COLUMN contact_user_name VARCHAR(255) NULL,
  ADD COLUMN dt_project_uuid CHAR(36) NULL,
  ADD COLUMN dt_project_name VARCHAR(255) NULL;

CREATE INDEX idx_kkg_application_dt_project ON kkg_application(dt_project_uuid);

CREATE TABLE kkg_application_tag (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id BIGINT NOT NULL,
  name VARCHAR(200) NOT NULL,
  description VARCHAR(1024) NULL,
  CONSTRAINT uk_kkg_application_tag_name UNIQUE (application_id, name),
  CONSTRAINT fk_kkg_application_tag_application
    FOREIGN KEY (application_id) REFERENCES kkg_application(id) ON DELETE CASCADE
);

ALTER TABLE kkg_scan
  ADD COLUMN dt_project_uuid CHAR(36) NULL,
  ADD COLUMN dt_bom_token CHAR(36) NULL,
  ADD COLUMN attempts INT NOT NULL DEFAULT 0,
  ADD COLUMN lease_owner VARCHAR(128) NULL,
  ADD COLUMN lease_expires_at TIMESTAMPTZ(3) NULL,
  ADD COLUMN submitted_at TIMESTAMPTZ(3) NULL,
  ADD COLUMN last_polled_at TIMESTAMPTZ(3) NULL,
  ADD COLUMN sbom_blob_store_id BIGINT NULL,
  ADD COLUMN sbom_blob_ref VARCHAR(1024) NULL,
  ADD COLUMN sbom_size BIGINT NULL;

CREATE INDEX idx_kkg_scan_submitted ON kkg_scan(status, submitted_at);
CREATE INDEX idx_kkg_scan_lease ON kkg_scan(status, lease_expires_at);
CREATE INDEX idx_kkg_scan_dedupe ON kkg_scan(application_id, source_id, sbom_sha256, status);

-- Compatibility privileges for the kkGuard /api/v2 surface. nx-admin gets them through nx-all;
-- no other role receives lifecycle access automatically.
INSERT INTO security_privilege
  (privilege_id, name, description, type, read_only, properties_json)
VALUES
  ('nx-lifecycle-read', 'nx-lifecycle-read', 'Read kkGuard applications and reports', 'application', true, jsonb_build_object('domain', 'lifecycle', 'actions', 'read')),
  ('nx-lifecycle-update', 'nx-lifecycle-update', 'Manage kkGuard applications and scans', 'application', true, jsonb_build_object('domain', 'lifecycle', 'actions', 'update,read'))
ON CONFLICT (privilege_id) DO NOTHING;

INSERT INTO security_role_privilege (role_id, privilege_id)
SELECT r.role_id, p.privilege_id
FROM security_role r CROSS JOIN security_privilege p
WHERE r.role_id = 'nx-admin'
  AND p.privilege_id IN ('nx-lifecycle-read', 'nx-lifecycle-update')
ON CONFLICT DO NOTHING;
