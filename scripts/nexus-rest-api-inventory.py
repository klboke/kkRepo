#!/usr/bin/env python3
"""Regenerate docs/en/dev/nexus-rest-api-inventory.md from the Nexus API client endpoint list.

The reference list is the README of sonatype-nexus-community/nexus-repo-api-client-go, which is
generated from a Nexus /service/rest/swagger.json. Override the URL with NEXUS_API_CLIENT_URL.
"""
import collections
import json
import os
import re
import sys
import urllib.request

DEFAULT_URL = (
    "https://raw.githubusercontent.com/sonatype-nexus-community/"
    "nexus-repo-api-client-go/main/README.md"
)
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, "docs/en/dev/nexus-rest-api-inventory.md")
SOURCE = os.environ.get("NEXUS_INVENTORY_SOURCE", os.path.join(ROOT, "server/src/main/java"))


def nexus_endpoints(url):
    body = urllib.request.urlopen(url, timeout=60).read().decode("utf-8", "replace")
    found = re.findall(r"\| \*\*(Get|Post|Put|Delete)\*\* (/v1/[^ |]+)", body)
    return sorted({(method.upper(), path) for method, path in found})


def kkrepo_endpoints():
    result = set()
    source = SOURCE
    for dirpath, _, files in os.walk(source):
        for name in files:
            if not name.endswith(".java"):
                continue
            text = open(os.path.join(dirpath, name), encoding="utf-8", errors="ignore").read()
            if "@RestController" not in text:
                continue
            class_mapping = re.search(
                r'@RequestMapping\(\s*(?:value\s*=\s*)?(\{[^}]*\}|"[^"]*")\s*\)', text)
            prefix = ""
            if class_mapping:
                values = re.findall(r'"([^"]+)"', class_mapping.group(1))
                prefix = values[0] if values else ""
            for kind, body in re.findall(
                    r"@(Get|Post|Put|Delete|Patch)Mapping(?:\(\s*(?:value\s*=\s*)?"
                    r"(\{[^}]*\}|\"[^\"]*\"|[^)]*)\))?", text, re.S):
                values = re.findall(r'"([^"]+)"', body or "") or [""]
                for value in values:
                    path = prefix.rstrip("/") + "/" + value.lstrip("/") if prefix else value
                    result.add((kind.upper(), path))
    return result


def normalize(path):
    return re.sub(r"\{[^}]+\}", "{}", path).rstrip("/")


def as_v1(path):
    if path.startswith("/v1/"):
        return path
    if path.startswith("/service/rest/v1/"):
        return path[len("/service/rest"):]
    return None


def main():
    url = os.environ.get("NEXUS_API_CLIENT_URL", DEFAULT_URL)
    nexus = [(m, p) for m, p in nexus_endpoints(url) if p.startswith("/v1/")]
    local = collections.defaultdict(set)
    for method, path in kkrepo_endpoints():
        value = as_v1(path)
        if value:
            local[method].add(normalize(value))
    rows = []
    for method, path in nexus:
        parts = [part for part in path.split("/") if part]
        area = parts[1] if len(parts) > 1 else path
        status = "yes" if normalize(path) in local.get(method, set()) else "no"
        rows.append((area, method, path, status))
    rows.sort(key=lambda row: (row[0], row[2], row[1]))
    lines = [
        "# Nexus Repository REST API inventory",
        "",
        "Generated by `scripts/nexus-rest-api-inventory.py` from the Sonatype Nexus Repository Go "
        "client endpoint list. `yes` means an exact method/path match exists under "
        "`/service/rest/v1`; `no` means the Nexus-shaped path is absent (functional equivalents "
        "may exist under `/internal`).",
        "",
        "| Area | Method | Path | kkRepo |",
        "| --- | --- | --- | --- |",
    ]
    lines += [f"| {area} | {method} | `{path}` | {status} |" for area, method, path, status in rows]
    with open(OUTPUT, "w", encoding="utf-8") as output:
        output.write("\n".join(lines) + "\n")
    matched = sum(1 for row in rows if row[3] == "yes")
    print(f"{matched}/{len(rows)} Nexus endpoints matched; wrote {OUTPUT}")
    areas = collections.defaultdict(lambda: [0, 0])
    for area, _, _, status in rows:
        areas[area][0] += 1
        if status == "yes":
            areas[area][1] += 1
    for area in sorted(areas, key=lambda name: -areas[name][0]):
        total, hit = areas[area]
        if total >= 2:
            print(f"  {hit}/{total} {area}")


if __name__ == "__main__":
    sys.exit(main())
